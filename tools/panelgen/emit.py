    def _fonts(self):
        bat = [n for n, _ in icons.BATTERY] + [icons.BATTERY_EMPTY, icons.BATTERY_UNKNOWN]
        self.g.add("_battery18", *bat)
        f = ['font:',
             '  # Roboto for text, Material Design Icons for glyphs. MDI is fetched from the',
             '  # webfont at build time and cached. `extras` ADDS to ESPHome\'s default ASCII',
             '  # set; `glyphs` would replace it and silently break every heading.',
             '  - file: "gfonts://Roboto"', '    id: font_xs', '    size: 18', '    extras:',
             '      - file: &mdi "https://github.com/Templarian/MaterialDesign-Webfont/raw/master'
             '/fonts/materialdesignicons-webfont.ttf"',
             '        glyphs: [' + ', '.join(f'"\\U000{c}"' for _, c in self.g.items("_battery18")) + ']']
        for fid, size in (("font_s", 22), ("font_m", 28), ("font_l", 48)):
            f += [f'  - file: "gfonts://Roboto"', f'    id: {fid}', f'    size: {size}',
                  '    extras:', '      - file: "gfonts://Roboto"',
                  '        glyphs: ["\\u00B0", "\\u2212"]   # degree sign, minus sign']
        f += ['  - file: "gfonts://Roboto"', '    id: font_step', '    size: 34',
              '    glyphs: ["+", "\\u2212"]']
        for fid, size in (("icon_m", 36), ("icon_l", 48)):
            items = self.g.items(fid)
            if not items:
                items = [("cog", icons.codepoint("cog"))]
            # The comma must precede the comment: in a YAML flow sequence a '#'
            # comments out the rest of the line, separator included.
            rows = [f'"\\U000{c}",   # mdi-{n}' for n, c in items]
            rows[-1] = rows[-1].replace('",   #', '"]   #', 1)
            f += [f'  - file: *mdi', f'    id: {fid}', f'    size: {size}',
                  '    glyphs: [' + rows[0]]
            f += ['             ' + r for r in rows[1:]]
        return f

    def _assemble(self):
        w = self.w
        w(HEAD)
        w("substitutions:")
        w(f"  name: {self.p.name}")
        w(f"  friendly_name: {_q(self.p.friendly_name)}")
        w("")
        w("packages:")
        for k in ("hardware", "network", "power", "ui", "light_sleep"):
            w(f"  {k}: !include base/{k}.yaml")
        w("")
        w("esphome:")
        w("  name: ${name}")
        w("  friendly_name: ${friendly_name}")
        w("  on_boot:")
        w("    priority: -100")
        w("    then:")
        w("      - lambda: |-")
        w("          ui_detheme_all();")
        w("          int p = id(last_page);")
        w(f"          if (p > 0 && p < {len(self.pages)})")
        w("            id(lv)->show_page(p, LV_SCREEN_LOAD_ANIM_NONE, 0);")
        w("          id(ui_ready) = true;")
        w("")
        if self.globals:
            w("globals:")
            [w(g) for g in self.globals]
            w("")
        names = ", ".join(_q(t) for t, _, _, _ in self.pages)
        self.text_sensors.append(
            "  - platform: template\n    id: current_page\n    name: Current page\n"
            "    entity_category: diagnostic\n    update_interval: 5s\n    lambda: |-\n"
            f"      static const char *names[] = {{{names}}};\n"
            "      int i = id(last_page);\n"
            f"      return std::string((i >= 0 && i < {len(self.pages)}) ? names[i] : \"?\");")
        for name, items in (("sensor", self.sensors), ("binary_sensor", self.binary_sensors),
                            ("text_sensor", self.text_sensors),
                            ("script", self.scripts), ("interval", self.intervals)):
            if items:
                w(f"{name}:")
                [w(i) for i in items]
                w("")
        [w(l) for l in self._fonts()]
        w("")
        w("select:")
        w("  - platform: template")
        w("    id: page_select")
        w("    name: Page")
        w("    optimistic: true")
        w("    entity_category: config")
        w("    options: [" + ", ".join(_q(t) for t, _, _, _ in self.pages) + "]")
        w(f"    initial_option: {_q(self.pages[0][0])}")
        w("    set_action:")
        w("      - lambda: |-")
        w("          auto idx = id(page_select).index_of(x);")
        w("          if (idx.has_value()) {")
        w("            id(lv)->show_page(*idx, LV_SCREEN_LOAD_ANIM_NONE, 0);")
        w("            id(inactivity).execute();")
        w("          }")
        w("")
        w("lvgl:")
        w("  pages:")
        for idx, (_t, _i, _p, body) in enumerate(self.pages):
            for line in body:
                w(line.replace("PAGEIDX", str(idx)))
        return "\n".join(self.out) + "\n"


