        self.g.add("icon_l", *icons.MEDIA_TRANSPORT)
        body = [f"    - id: {pid}", "      bg_color: ${paper}", "      bg_opa: COVER",
                "      on_load:", "        - lambda: 'if (id(ui_ready)) id(last_page) = PAGEIDX;'",
                f"        - lvgl.widget.refresh: [p{pi}_state, p{pi}_title]",
                "      widgets:",
                f"        - label: {{ x: {L.MARGIN}, y: {L.HEADING_Y}, styles: heading,"
                f" text: {_q(page.title)} }}"]
        body += self.card(L.MARGIN, L.CARD_TOP, L.CONTENT_W, L.MEDIA_CARD_H) + [
            f"              - label: {{ x: 0, y: 2, text: {_lit(icons.escape('television'))}, text_font: icon_m }}",
            f"              - label: {{ x: 48, y: 6, text: {_q(page.label)}, text_font: font_m }}",
            "              - label:", f"                  id: p{pi}_title", "                  x: 0",
            "                  y: 62", "                  width: 386", "                  long_mode: WRAP",
            "                  text_font: font_s",
            f"                  text: !lambda 'return id(p{pi}_title_src).state;'",
            "              - label:", f"                  id: p{pi}_state",
            "                  align: BOTTOM_LEFT", "                  text_font: font_s",
            f"                  text: !lambda 'return id(p{pi}_state_src).state;'"]
        actions = [("skip-previous", "media_previous_track"), ("play-pause", "media_play_pause"),
                   ("skip-next", "media_next_track"), ("volume-minus", "volume_down"),
                   ("volume-off", "volume_mute"), ("volume-plus", "volume_up")]
        for i, (icon, action) in enumerate(actions):
            x, y = L.MEDIA_BTN_X[i % 3], L.MEDIA_ROW_Y[i // 3]
            press = ["on_press:", "  - script.execute: inactivity"]
            if action == "volume_mute":
                # media_player.volume_mute REQUIRES is_volume_muted, and it sets an
                # absolute state rather than toggling - so send the inverse of what
                # the player currently reports.
                press += ["  - homeassistant.action:",
                          f"      action: media_player.{action}",
                          "      data_template:",
                          f"        entity_id: {page.entity}",
                          '        is_volume_muted: "{{ muted }}"',
                          "      variables:",
                          f"        muted: !lambda 'return id(p{pi}_muted).state"
                          ' ? std::string("false") : std::string("true");\'']
            else:
                press += [f"  - homeassistant.action: {{ action: media_player.{action},"
                          f" data: {{ entity_id: {page.entity} }} }}"]
            body += self.button(x, y, L.MEDIA_BTN_W, L.MEDIA_BTN_H, extra=[
                f"widgets: [ {{ label: {{ align: CENTER, text: {_lit(icons.escape(icon))},"
                " text_font: icon_l } } ]", *press])
        self.binary_sensors.append(
            f"  - platform: homeassistant\n    id: p{pi}_muted\n"
            f"    entity_id: {page.entity}\n    attribute: is_volume_muted")
        for role, attr in (("state", None), ("title", "media_title")):
            a = f"\n    attribute: {attr}" if attr else ""
            self.text_sensors.append(
                f"  - platform: homeassistant\n    id: p{pi}_{role}_src\n"
                f"    entity_id: {page.entity}{a}\n"
                f"    on_value: {{ then: [ lvgl.widget.refresh: p{pi}_{role} ] }}")
        return [(page.title, page.icon, pid, body)]

