    # -- Readouts -----------------------------------------------------------
    def _page_readouts(self, pi, page):
        out = []
        for sp, placed in enumerate(L.paginate_readouts(page.entities, page.columns)):
            pid = f"page_p{pi}_{sp}"
            title = page.title if sp == 0 else f"{page.title} {sp + 1}"
            ids = [f"p{pi}e{page.entities.index(t.item)}_val" for t in placed]
            body = [f"    - id: {pid}", "      bg_color: ${paper}", "      bg_opa: COVER",
                    "      on_load:", "        - lambda: 'if (id(ui_ready)) id(last_page) = PAGEIDX;'",
                    f"        - lvgl.widget.refresh: [{', '.join(ids)}]",
                    "      widgets:",
                    f"        - label: {{ x: {L.MARGIN}, y: {L.HEADING_Y}, styles: heading,"
                    f" text: {_q(page.title)} }}"]
            for t in placed:
                e = t.item
                ei = page.entities.index(e)
                self.g.add("icon_m", e.icon)
                vfont = "font_l" if page.columns == 1 else "font_m"
                if page.columns == 1:
                    inner = [f"              - label: {{ align: LEFT_MID, text: {_lit(icons.escape(e.icon))},"
                             " text_font: icon_m }",
                             f"              - label: {{ align: LEFT_MID, x: 48, text: {_q(e.label)},"
                             " text_font: font_s }",
                             "              - label:", f"                  id: p{pi}e{ei}_val",
                             "                  align: RIGHT_MID", f"                  text_font: {vfont}"]
                else:
                    inner = [f"              - label: {{ x: 0, y: 0, text: {_lit(icons.escape(e.icon))},"
                             " text_font: icon_m }",
                             f"              - label: {{ x: 0, y: 40, text: {_q(e.label)}, text_font: font_s }}",
                             "              - label:", f"                  id: p{pi}e{ei}_val",
                             "                  align: TOP_RIGHT", f"                  text_font: {vfont}"]
                if len(e.entity) == 1:
                    inner.append(
                        f"                  text: !lambda 'const float v = id(p{pi}e{ei}_src0).state;"
                        f" return std::isnan(v) ? std::string(\"--\") : str_sprintf({_q(e.format[0])}, v);'")
                else:
                    inner += ["                  text: !lambda |-",
                              f"                    const float a = id(p{pi}e{ei}_src0).state,"
                              f" b = id(p{pi}e{ei}_src1).state;",
                              "                    if (std::isnan(a) && std::isnan(b)) return std::string(\"--\");",
                              "                    const float av = std::isnan(a) ? 0.0f : a,"
                              " bv = std::isnan(b) ? 0.0f : b;",
                              f"                    return bv > av ? str_sprintf({_q(e.format[1])}, bv)",
                              f"                                  : str_sprintf({_q(e.format[0])}, av);"]
                body += self.card(t.x, t.y, t.w, t.h, pad=12) + inner
                for k, ent in enumerate(e.entity):
                    attr = f"\n    attribute: {e.attribute[k]}" if e.attribute[k] else ""
                    self.sensors.append(
                        f"  - platform: homeassistant\n    id: p{pi}e{ei}_src{k}\n"
                        f"    entity_id: {ent}{attr}")
            self.intervals.append(
                f"  - interval: 60s\n    then:\n      - if:\n          condition:\n"
                f"            lambda: 'return lv_screen_active() == id({pid})->obj;'\n"
                f"          then: [ lvgl.widget.refresh: [{', '.join(ids)}] ]")
            out.append((title, page.icon, pid, body))
        return out

