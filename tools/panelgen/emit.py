def _q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _lit(esc):
    """Quote an already-formed \\U000F.... escape WITHOUT re-escaping its backslash.

    _q is for human text. Using it on a glyph escape yields "\\\\U000F0336", which
    YAML decodes to the literal ten characters rather than the icon - it compiles
    happily and draws nonsense on the panel.
    """
    return '"' + esc + '"'


class Emitter:
    def __init__(self, panel):
        self.p = panel
        self.g = icons.GlyphSets()
        self.out = []
        self.sensors = []
        self.text_sensors = []
        self.binary_sensors = []
        self.pages = []          # (title, icon, page_id)
        self.scripts = []
        self.intervals = []
        self.globals = []

    # ---------------------------------------------------------------- helpers
    def w(self, s=""):
        self.out.append(s)

    def card(self, x, y, w, h, pad=14, extra=()):
        b = [f"        - obj:", "            styles: tile", "            scrollable: false",
             f"            x: {x}", f"            y: {y}",
             f"            width: {w}", f"            height: {h}",
             f"            pad_all: {pad}"]
        b += [f"            {e}" for e in extra]
        b.append("            widgets:")
        return b

    def button(self, x, y, w, h, style="navbtn", extra=()):
        b = [f"        - button:", f"            styles: {style}",
             "            pressed: { styles: tile_on }",
             f"            x: {x}", f"            y: {y}",
             f"            width: {w}", f"            height: {h}"]
        b += [f"            {e}" for e in extra]
        return b

    # ------------------------------------------------------------------ pages
    def build(self):
        seq = []
        for pi, page in enumerate(self.p.pages):
            fn = getattr(self, f"_page_{page.type}")
            seq.extend(fn(pi, page))
        seq.extend(self._page_settings(len(self.p.pages)))

        nav = L.paginate_nav(len(seq), bool(self.p.summary))
        home = self._page_home(nav, seq)
        self.pages = home + seq
        return self._assemble()

    # -- Home ---------------------------------------------------------------
    def _page_home(self, nav_pages, seq):
        out = []
        for hp, tiles in enumerate(nav_pages):
            pid = f"page_home{'' if hp == 0 else hp + 1}"
            body = [f"    - id: {pid}", "      bg_color: ${paper}", "      bg_opa: COVER",
                    "      on_load:",
                    f"        - lambda: 'if (id(ui_ready)) id(last_page) = {len(out)};'"]
            if self.p.summary and hp == 0:
                body.append("        - script.execute: home_summary")
            body.append("      widgets:")
            for t in tiles:
                title, icon, target = seq[t.item][:3]
                self.g.add("icon_l", icon)
                body += self.button(t.x, t.y, t.w, t.h, "tile", extra=[
                    "pad_all: 6", "layout:", "  type: FLEX", "  flex_flow: COLUMN",
                    "  flex_align_main: CENTER", "  flex_align_cross: CENTER",
                    "  flex_align_track: CENTER", "  pad_row: 8", "widgets:",
                    f"  - label: {{ text: {_lit(icons.escape(icon))}, text_font: icon_l }}",
                    f"  - label: {{ text: {_q(title)}, text_font: font_m }}",
                    "on_press:", "  - script.execute: inactivity",
                    f"  - lvgl.page.show: {target}"])
            if self.p.summary and hp == 0:
                body += self._summary_card()
            out.append(("Home" if hp == 0 else f"Home {hp+1}", "home", pid, body))
        return [(t, i, p, b) for t, i, p, b in out]

    def _summary_card(self):
        cells, body = self.p.summary, self.card(L.MARGIN, L.SUMMARY_Y, L.CONTENT_W, L.SUMMARY_H)
        checks = []
        for i, c in enumerate(cells):
            x, y = (0 if i % 2 == 0 else 200), (0 if i < 2 else 116)
            body += [f"              - label: {{ x: {x}, y: {y}, text: {_q(c.label)}, text_font: font_s }}",
                     "              - label:", f"                  id: sum{i}_val",
                     f"                  x: {x}", f"                  y: {y + 28}",
                     "                  text_font: font_l", "                  text: !lambda |-"]
            if c.source == "lights_on":
                ids = ", ".join(f"id({e})" for e in self._light_state_ids())
                body += [f"                    int v = 0;",
                         f"                    for (auto *t : {{{ids}}}) if (t->state == \"on\") v++;",
                         f"                    return str_sprintf(\"%d on\", v);"]
                checks.append((i, f"""int v = 0;
              for (auto *t : {{{ids}}}) if (t->state == "on") v++;
              if (v == id(sum{i}_shown)) return false;
              id(sum{i}_shown) = v;
              return true;"""))
            else:
                sid = self._sensor(c.entity, c.attribute)
                body += [f"                    const float x = id({sid}).state;",
                         f"                    return std::isnan(x) ? std::string(\"--\") : str_sprintf({_q(c.format)}, x);"]
                checks.append((i, f"""const float x = id({sid}).state;
              const int v = std::isnan(x) ? -99999 : (int) lroundf(x * 100.0f);
              if (v == id(sum{i}_shown)) return false;
              id(sum{i}_shown) = v;
              return true;"""))
            self.globals.append(f"  - id: sum{i}_shown\n    type: int\n    initial_value: \"-99999\"")

        s = ["  - id: home_summary", "    then:"]
        for i, cond in checks:
            s += ["      - if:", "          condition:", "            lambda: |-",
                  *[f"              {ln}" for ln in cond.strip().splitlines()],
                  f"          then: [ lvgl.widget.refresh: sum{i}_val ]"]
        self.scripts.append("\n".join(s))
        self.intervals.append(
            "  - interval: 30s\n    then:\n      - if:\n          condition:\n"
            "            lambda: 'return lv_screen_active() == id(page_home)->obj;'\n"
            "          then: [ script.execute: home_summary ]")
        return body

    def _light_state_ids(self):
        ids = []
        for pi, page in enumerate(self.p.pages):
            if page.type == "lights":
                ids += [f"p{pi}e{ei}_state" for ei in range(len(page.entities))]
        return ids or ["battery_level"]        # never emit an empty initialiser list

